import java.security.MessageDigest
import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

/**
 * Generates `Allowlist.kt` (object `asc.asc.ui.GeneratedAllowlist`) and the classpath resource
 * `asc/asc/allowlist.json` from the one checked-in source, `allowlist.json` (SPEC 24.4.5.1).
 *
 * The source text is embedded byte for byte with its SHA-256, so the Kotlin copy cannot drift from the source:
 * AllowlistTest recomputes both from the file. The task parses nothing; the relay's `Allowlist.parse` is the
 * only reader, which keeps one parser. A missing or empty source fails the build rather than emitting an empty
 * allowlist.
 */
@CacheableTask
abstract class GenerateAllowlistTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val source: RegularFileProperty

    @get:OutputDirectory
    abstract val kotlinDir: DirectoryProperty

    @get:OutputDirectory
    abstract val resourceDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val bytes = source.get().asFile.readBytes()
        require(bytes.isNotEmpty()) { "allowlist.json is empty" }
        val text = String(bytes, Charsets.UTF_8)
        require(text.toByteArray(Charsets.UTF_8).contentEquals(bytes)) { "allowlist.json is not valid UTF-8" }
        val sha = MessageDigest.getInstance("SHA-256").digest(bytes).joinToString("") { "%02x".format(it) }

        val kotlinOut = kotlinDir.get().asFile.resolve("asc/asc/ui")
        kotlinOut.deleteRecursively()
        kotlinOut.mkdirs()
        kotlinOut.resolve("Allowlist.kt").writeText(render(text, sha), Charsets.UTF_8)

        val resOut = resourceDir.get().asFile.resolve("asc/asc")
        resOut.deleteRecursively()
        resOut.mkdirs()
        resOut.resolve("allowlist.json").writeBytes(bytes)
    }

    private fun render(text: String, sha: String): String {
        // A JVM string constant is capped at 65535 UTF-8 bytes, so the text is emitted in short literal chunks.
        val chunks = text.chunked(2000).joinToString(",\n") { "        " + literal(it) }
        return buildString {
            appendLine("// GENERATED by the Gradle task generateAllowlist (P48) from allowlist.json. Do not edit.")
            appendLine("package asc.asc.ui")
            appendLine()
            appendLine("object GeneratedAllowlist {")
            appendLine("    /** SHA-256 (hex) of the source allowlist.json bytes. */")
            appendLine("    const val SHA256: String = \"$sha\"")
            appendLine()
            appendLine("    /** The source allowlist.json text, verbatim. */")
            appendLine("    val JSON: String = listOf(")
            appendLine(chunks)
            appendLine("    ).joinToString(\"\")")
            appendLine()
            appendLine("    /** The checked relay table; throws if the embedded text is malformed. */")
            appendLine("    fun parse(): Allowlist = Allowlist.parse(JSON)")
            appendLine("}")
        }
    }

    private fun literal(s: String): String {
        val sb = StringBuilder("\"")
        for (c in s) {
            when {
                c == '\\' -> sb.append("\\\\")
                c == '"' -> sb.append("\\\"")
                c == '$' -> sb.append("\\$")
                c == '\n' -> sb.append("\\n")
                c == '\r' -> sb.append("\\r")
                c == '\t' -> sb.append("\\t")
                c.code < 0x20 || c.code > 0x7e -> sb.append("\\u%04x".format(c.code))
                else -> sb.append(c)
            }
        }
        return sb.append('"').toString()
    }
}
